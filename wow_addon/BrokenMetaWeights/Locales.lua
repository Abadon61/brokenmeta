-- there falls back to English), English for every other client.
local _, ns = ...
local LOCALE = GetLocale()
ns.IS_FR = LOCALE == "frFR"

local EXTRA = {}

function ns.Localize(section, fr, en)
  if LOCALE == "frFR" then return fr end
  local extra = EXTRA[LOCALE] and EXTRA[LOCALE][section]
  if not extra then return en end
  return setmetatable(extra, { __index = en })
end

