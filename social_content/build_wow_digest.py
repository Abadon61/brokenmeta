"""
BrokenMeta Content Studio - WoW: Forever digest
================================================
Facts for the WoW: Forever social cards, written to social_content/wow_digest.json
(the card_wow_*.html templates fetch it, so a refresh needs no HTML edit).

    py social_content/build_wow_digest.py                 # ranking as shown LIVE on brokenmeta.gg
    py social_content/build_wow_digest.py --source working  # newest local simulation (not deployed yet)

Why two sources: data/wow_ranking60.json is regenerated by the level-60 simulator
and is often ahead of what is deployed. A post must quote what visitors can verify
on the site today, so the default reads the version COMMITTED in git HEAD (which is
what gets deployed); use --source working only once that simulation has been deployed.

The numbers are SIMULATION results (not real logs): the cards say so.
"""
import argparse
import json
import math
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = Path(__file__).resolve().parent / "wow_digest.json"

LAUNCH_UTC = datetime(2026, 11, 4, 23, 0, tzinfo=timezone.utc)   # 15:00 PST, as stated by Blizzard (site_build/wow_content.py LAUNCH_UTC)
BETA_END = "21 octobre 2026"                                       # Blizzard; site_build/wow_content.py documents the 22 Oct (Icy Veins) conflict

# Copied from site_build/build_site.py (SIM60_RANK_SPECS / SIM60_SUFFIX): simulator spec id -> (class id, Forever spec id, suffix key)
SPECS = {
    "warrior_fury": ("warrior", "fury", ""), "warrior_arms": ("warrior", "arms", ""), "warrior_protection": ("warrior", "protection", ""),
    "rogue_combat": ("rogue", "combat", ""), "rogue_assassination": ("rogue", "assassination", ""), "rogue_subtlety": ("rogue", "subtlety", ""),
    "mage_fire": ("mage", "fire", ""), "mage_frost": ("mage", "frost", ""), "mage_arcane": ("mage", "arcane", ""),
    "warlock_affliction": ("warlock", "affliction", ""), "warlock_destruction": ("warlock", "destruction", ""), "warlock_demonology": ("warlock", "demonology", ""),
    "hunter_marksmanship": ("hunter", "marksmanship", ""), "hunter_beastmastery": ("hunter", "beast-mastery", ""), "hunter_melee": ("hunter", "survival", ""),
    "priest_shadow": ("priest", "shadow", ""), "shaman_elemental": ("shaman", "elemental", ""), "shaman_enhancement": ("shaman", "enhancement", ""),
    "druid_balance": ("druid", "balance", ""), "druid_feral": ("druid", "feral-combat", ""), "druid_bear": ("druid", "feral-combat", "bear"), "paladin_retribution": ("paladin", "retribution", ""),
    "paladin_protection": ("paladin", "protection", ""),
}
SUFFIX_FR = {"ranged": " (distance)", "melee": " (mêlée)", "bear": " (ours)"}


def load_ranking(source):
    if source == "working":
        return json.loads((ROOT / "data" / "wow_ranking60.json").read_text(encoding="utf-8"))
    raw = subprocess.run(["git", "show", "HEAD:data/wow_ranking60.json"], cwd=ROOT, capture_output=True, check=True).stdout
    return json.loads(raw.decode("utf-8"))


def class_info(class_id):
    d = json.loads((ROOT / "data" / "wow_talents" / f"{class_id}.json").read_text(encoding="utf-8"))
    return d["name"]["fr"], d["color"], {s["id"]: s["name"]["fr"] for s in d["specs"]}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--source", choices=["live", "working"], default="live")
    ap.add_argument("--date", help="override 'today' (YYYY-MM-DD) for the countdown")
    args = ap.parse_args()

    data = load_ranking(args.source)
    dps_rows, tank_rows = [], []
    for r in data["specs"]:
        m = SPECS.get(r["spec"])
        if not m:
            continue
        cls_id, spec_id, suffix = m
        cls_fr, color, spec_names = class_info(cls_id)
        row = {
            "spec_id": r["spec"], "class_id": cls_id, "class_color": color,
            "label": f"{cls_fr} — {spec_names.get(spec_id, spec_id)}{SUFFIX_FR.get(suffix, '')}",
            "icon": f"../logo/wow_spec_icons/{cls_id}-{spec_id}.png", "role": r["role"],
        }
        if r["role"] == "tank":
            row.update({"value": r["tps"], "dtps": r["dtps"], "health": r["health"]})
            tank_rows.append(row)
        else:
            row.update({"value": r["dps"]})
            dps_rows.append(row)
    dps_rows.sort(key=lambda x: x["value"], reverse=True)
    tank_rows.sort(key=lambda x: x["value"], reverse=True)

    today = datetime.strptime(args.date, "%Y-%m-%d").replace(tzinfo=timezone.utc) if args.date else datetime.now(timezone.utc)
    days_left = max(0, math.floor((LAUNCH_UTC - today).total_seconds() / 86400))

    digest = {
        "generated_for": today.strftime("%Y-%m-%d"),
        "ranking_source": args.source,
        "simulation": {"date": data.get("generated"), "build": data.get("build"), "fight_seconds": data.get("fightLen"), "iterations": data.get("iterations")},
        "dps": dps_rows,
        "tanks": tank_rows,
        "countdown": {"days_left": days_left, "launch_label": "4 novembre 2026, 15 h (heure du Pacifique)", "launch_paris": "minuit à Paris",
                      "beta": f"17 septembre → {BETA_END}"},
    }
    OUT.write_text(json.dumps(digest, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"wow_digest.json written (source={args.source}, sim {data.get('generated')}, J-{days_left}); top DPS: "
          + ", ".join(f"{r['label']} {r['value']:.0f}" for r in dps_rows[:3]))


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    main()
